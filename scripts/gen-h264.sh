#!/bin/sh
# Generates prebuilt H.264 replacement streams for each WebRTC adaptation
# resolution and emits them as Rust source.  Run as:
#
#   ./scripts/gen-h264.sh > tun/src/protozoa/h264_tables.rs
#
# Each stream is a single-slice, CAVLC/baseline, no-B-frame GOP of a static
# black picture: one SPS, one PPS, one IDR slice, then a run of P-slices.
# hook_before_h264_reference_find replays them to keep the peer's FFmpeg
# decoder fed with a valid bitstream while the real payload carries tunnel
# data.  Single slice per frame keeps NAL framing predictable; CAVLC keeps the
# P-slices tiny and uniform.
#
# Requires: ffmpeg with libx264, python3
set -eu

# Frames of P-slice run to capture per resolution.  The replay loop wraps back
# to the IDR at the end, so this only bounds how long we can go between real
# keyframe carriers before injecting an unsolicited IDR.
PRUN=256
# GOP length handed to x264; must exceed PRUN so the captured run has no
# mid-stream IDR.
KEYINT=$((PRUN + 32))

# Include the cropped 480x264 size observed during encoder adaptation as well
# as the nominal 480x270 step. These must remain distinct replay streams.
SIZES="1280x720 960x540 640x360 480x270 480x264 320x180 240x135"

cat <<'EOF'
// Auto-generated by scripts/gen-h264.sh — do not edit manually.
// Regenerate with: ./scripts/gen-h264.sh > tun/src/protozoa/h264_tables.rs
//
// One static-picture baseline/CAVLC GOP per resolution in libwebrtc's
// VideoAdapter down-step sequence.  NAL bodies are stored without start codes
// or the 1-byte NAL header (see PrebuiltH264Stream); h264.rs prepends a
// 4-byte Annex-B start code and the recorded header byte at replay time.
//
// This file is `include!`d by h264.rs, so it carries no inner attributes.

pub struct PrebuiltH264Nal<'a> {
    /// NAL header byte (forbidden_zero_bit | nal_ref_idc | nal_unit_type).
    pub header: u8,
    /// RBSP bytes following the header, emulation-prevention already applied.
    pub body: &'a [u8],
}

pub struct PrebuiltH264Stream<'a> {
    pub width: u16,
    pub height: u16,
    pub sps: PrebuiltH264Nal<'a>,
    pub pps: PrebuiltH264Nal<'a>,
    pub idr: PrebuiltH264Nal<'a>,
    /// P-slices in decode order; replayed round-robin between IDR injections.
    pub deltas: &'a [PrebuiltH264Nal<'a>],
}
EOF

printf '\n#[rustfmt::skip]\npub const H264_STATIC_STREAMS: &[PrebuiltH264Stream] = &[\n'

for size in $SIZES; do
    w=${size%x*}
    h=${size#*x}
    # H.264 requires even dimensions; libwebrtc crops odd adaptation steps down.
    enc_w=$((w - w % 2))
    enc_h=$((h - h % 2))
    raw=$(mktemp /tmp/gen-h264.XXXXXX.264)
    ffmpeg -hide_banner -loglevel error -y \
        -fflags +bitexact -flags:v +bitexact \
        -f lavfi -i "color=c=black:size=${enc_w}x${enc_h}:rate=30" \
        -frames:v "$KEYINT" \
        -c:v libx264 -profile:v baseline -preset veryfast -tune zerolatency \
        -threads 1 \
        -x264-params "keyint=${KEYINT}:min-keyint=${KEYINT}:scenecut=0:bframes=0:ref=1:aud=0:repeat-headers=1:sliced-threads=0:sync-lookahead=0:rc-lookahead=0:cabac=0:weightp=0:8x8dct=0" \
        -f h264 "$raw"

    W="$enc_w" H="$enc_h" PRUN="$PRUN" RAW="$raw" python3 - <<'PY'
import os, re, sys

raw = open(os.environ["RAW"], "rb").read()
os.unlink(os.environ["RAW"])
w, h, prun = int(os.environ["W"]), int(os.environ["H"]), int(os.environ["PRUN"])

# Split Annex-B into NAL units (strip 3- or 4-byte start codes).
starts = [m.start() for m in re.finditer(b"\x00\x00\x01", raw)]
nals = []
for i, s in enumerate(starts):
    body_start = s + 3
    end = starts[i + 1] if i + 1 < len(starts) else len(raw)
    # trailing 0x00 belongs to the next 4-byte start code
    if i + 1 < len(starts) and raw[starts[i + 1] - 1] == 0:
        end -= 1
    nal = raw[body_start:end]
    if nal:
        nals.append(nal)

def take(nal_type):
    for n in nals:
        if n[0] & 0x1F == nal_type:
            return n
    sys.exit(f"no NAL type {nal_type} for {w}x{h}")

sps = take(7)
pps = take(8)
idr = take(5)
deltas = [n for n in nals if n[0] & 0x1F == 1][:prun]
if len(deltas) < prun:
    sys.exit(f"only {len(deltas)} P-slices for {w}x{h}, need {prun}")

def rust_bytestr(b):
    return '"' + "".join(f"\\x{x:02x}" for x in b) + '"'

def emit_nal(name, nal, indent):
    pad = " " * indent
    body = nal[1:]
    print(f"{pad}{name}PrebuiltH264Nal {{ header: 0x{nal[0]:02x}, body: b{rust_bytestr(body)} }},")

print("    PrebuiltH264Stream {")
print(f"        width: {w},")
print(f"        height: {h},")
emit_nal("sps: ", sps, 8)
emit_nal("pps: ", pps, 8)
emit_nal("idr: ", idr, 8)
print("        deltas: &[")
for d in deltas:
    emit_nal("", d, 12)
print("        ],")
print("    },")
PY
done

printf '];\n'
